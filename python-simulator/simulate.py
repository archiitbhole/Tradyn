"""Tradyn Simulator — the original Python engine, run from the terminal (no server, no internet).

    python simulate.py                       one run (40 traders, 500 steps, market shock at 45%)
    python simulate.py --steps 800 --seed 7  change the run
    python simulate.py --export out/         also save the CSV tables
    python -m tradyn.experiments --help      Experiment Lab: scenarios and the trader-mix sweep

Simulation only — every price here is generated by rule-based traders, not real market data.
"""

from __future__ import annotations

import argparse

from tradyn.config import VOLATILITY_LEVELS, SimConfig


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description="Tradyn Simulator — an artificial stock market with rule-based traders.")
    ap.add_argument("--traders", type=int, default=40)
    ap.add_argument("--steps", type=int, default=500)
    ap.add_argument("--price", type=float, default=100.0, help="initial (simulated) price")
    ap.add_argument("--volatility", choices=list(VOLATILITY_LEVELS), default="Medium")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--no-shock", action="store_true", help="do not trigger the market shock at 45%% of the run")
    ap.add_argument("--export", metavar="FOLDER", help="also save CSV files to this folder")
    a = ap.parse_args(argv)

    import pandas as pd

    from tradyn.analysis import export_csv, market_summary, strategy_summary
    from tradyn.market import MarketEngine

    cfg = SimConfig(n_traders=a.traders, steps=a.steps, initial_price=a.price, volatility=a.volatility, seed=a.seed)
    schedule = {} if a.no_shock else {round(0.45 * a.steps): "shock"}
    engine = MarketEngine(cfg).run(schedule=schedule)
    pd.set_option("display.width", 120)
    print("\nSIMULATION MODE — artificial market, not real prices")
    print(f"\nMARKET SUMMARY{'' if a.no_shock else ' (market shock at 45% of the run)'}")
    for k, v in market_summary(engine).items():
        print(f"  {k:<36} {v:,.2f}" if isinstance(v, float) else f"  {k:<36} {v:,}")
    print("\nSTRATEGY SUMMARY")
    print(strategy_summary(engine).round(2).to_string())
    if a.export:
        for p in export_csv(engine, a.export):
            print("saved", p)
    print("\nSimulation only — not a prediction of real markets.")


if __name__ == "__main__":
    main()
