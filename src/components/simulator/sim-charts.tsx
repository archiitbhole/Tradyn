"use client";
import { Area, Bar, CartesianGrid, ComposedChart, Legend, Line, LineChart, ReferenceArea, ReferenceLine, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { STRATEGY_NAMES } from "@/lib/simulator/config";
import { downsample, rolling } from "@/lib/simulator/analysis";
import { EVENTS, type MarketEngine } from "@/lib/simulator/engine";
import type { ScenarioResult, SweepResult } from "@/lib/simulator/experiments";
import { AXIS_TICK, STRATEGY_COLOR, TOOLTIP_STYLE, simNum, simPct } from "./sim-format";

const GRID = "var(--border)";
const EVENT_FILL: Record<string, string> = { positive: "var(--up)", bull: "var(--up)", negative: "var(--down)", shock: "var(--down)" };

/**
 * Simulated price with its 20-step average and shaded event windows. The axis is labelled "sim"
 * on purpose: these numbers are generated by the simulator and are never real share prices.
 */
export function SimPriceChart({ engine, height = 300 }: { engine: MarketEngine; height?: number }) {
  const avg = rolling(engine.prices, 20);
  const idx = downsample(engine.prices.length, 500);
  const data = idx.map((i) => ({ step: i, price: engine.prices[i], avg: avg[i] }));
  const start = engine.cfg.initialPrice;
  return (
    <div style={{ height }} data-testid="sim-price-chart">
      <ResponsiveContainer width="100%" height="100%">
        <LineChart data={data} margin={{ top: 8, right: 8, left: 0, bottom: 0 }}>
          <CartesianGrid stroke={GRID} strokeDasharray="3 3" vertical={false} />
          <XAxis dataKey="step" type="number" domain={[0, engine.cfg.steps]} tick={AXIS_TICK} tickLine={false} axisLine={false} />
          <YAxis domain={["auto", "auto"]} tick={AXIS_TICK} tickLine={false} axisLine={false} width={56} tickFormatter={(v: number) => simNum(v)} />
          {engine.eventLog.map((ev, i) => (
            <ReferenceArea key={i} x1={ev.step} x2={Math.min(engine.cfg.steps, ev.step + ev.duration)} fill={EVENT_FILL[ev.key]} fillOpacity={0.1} strokeOpacity={0} ifOverflow="hidden" />
          ))}
          <ReferenceLine y={start} stroke="var(--faint)" strokeDasharray="4 4" label={{ value: `start ${simNum(start)}`, position: "insideTopLeft", fill: "var(--faint)", fontSize: 11 }} />
          <Tooltip contentStyle={TOOLTIP_STYLE} labelFormatter={(s) => `Step ${s}`} formatter={(v, name) => [simNum(Number(v)), name === "price" ? "Sim price" : "20-step average"]} />
          <Line dataKey="avg" stroke="var(--faint)" strokeWidth={1.25} dot={false} isAnimationActive={false} />
          <Line dataKey="price" stroke="var(--sim)" strokeWidth={2} dot={false} isAnimationActive={false} />
        </LineChart>
      </ResponsiveContainer>
    </div>
  );
}

/** Buy and sell pressure (shares) for the last 80 steps, with net demand as a line. */
export function PressureChart({ engine, height = 180 }: { engine: MarketEngine; height?: number }) {
  const rows = engine.history.slice(-80).filter((r) => r.step > 0);
  const data = rows.map((r) => ({ step: r.step, buy: r.buyPressure, sell: -r.sellPressure, net: r.netDemand }));
  return (
    <div style={{ height }}>
      <ResponsiveContainer width="100%" height="100%">
        <ComposedChart data={data} margin={{ top: 4, right: 4, left: 0, bottom: 0 }} stackOffset="sign">
          <CartesianGrid stroke={GRID} strokeDasharray="3 3" vertical={false} />
          <XAxis dataKey="step" tick={AXIS_TICK} tickLine={false} axisLine={false} minTickGap={24} />
          <YAxis tick={AXIS_TICK} tickLine={false} axisLine={false} width={40} />
          <ReferenceLine y={0} stroke="var(--border-strong)" />
          <Tooltip contentStyle={TOOLTIP_STYLE} labelFormatter={(s) => `Step ${s}`} formatter={(v, name) => [Math.abs(Number(v)), name === "buy" ? "Bought" : name === "sell" ? "Sold" : "Net demand"]} />
          <Bar dataKey="buy" stackId="p" fill="var(--up)" fillOpacity={0.75} isAnimationActive={false} />
          <Bar dataKey="sell" stackId="p" fill="var(--down)" fillOpacity={0.75} isAnimationActive={false} />
          <Line dataKey="net" stroke="var(--foreground)" strokeWidth={1.25} dot={false} isAnimationActive={false} />
        </ComposedChart>
      </ResponsiveContainer>
    </div>
  );
}

/** Average portfolio value of each strategy's traders over the run. */
export function GrowthChart({ engine, height = 260 }: { engine: MarketEngine; height?: number }) {
  const idx = downsample(engine.history.length, 300);
  const data = idx.map((i) => {
    const row: Record<string, number | null> = { step: engine.history[i].step };
    for (const n of STRATEGY_NAMES) row[n] = engine.growth[n][i];
    return row;
  });
  const present = STRATEGY_NAMES.filter((n) => engine.growth[n].some((v) => v != null));
  return (
    <div style={{ height }}>
      <ResponsiveContainer width="100%" height="100%">
        <LineChart data={data} margin={{ top: 8, right: 8, left: 0, bottom: 0 }}>
          <CartesianGrid stroke={GRID} strokeDasharray="3 3" vertical={false} />
          <XAxis dataKey="step" type="number" domain={["dataMin", "dataMax"]} tick={AXIS_TICK} tickLine={false} axisLine={false} />
          <YAxis domain={["auto", "auto"]} tick={AXIS_TICK} tickLine={false} axisLine={false} width={64} tickFormatter={(v: number) => simNum(v)} />
          <Tooltip contentStyle={TOOLTIP_STYLE} labelFormatter={(s) => `Step ${s}`} formatter={(v, name) => [simNum(Number(v)), String(name)]} />
          <Legend wrapperStyle={{ fontSize: 12 }} />
          {present.map((n) => <Line key={n} dataKey={n} stroke={STRATEGY_COLOR[n]} strokeWidth={1.75} dot={false} isAnimationActive={false} />)}
        </LineChart>
      </ResponsiveContainer>
    </div>
  );
}

/** Experiment Lab: the middle 80% of simulated price paths (10th–90th percentile) and the median. */
export function BandChart({ result, height = 260 }: { result: ScenarioResult; height?: number }) {
  const data = result.x.map((step, i) => ({ step, band: [result.p10[i], result.p90[i]] as [number, number], p50: result.p50[i] }));
  return (
    <div style={{ height }}>
      <ResponsiveContainer width="100%" height="100%">
        <ComposedChart data={data} margin={{ top: 8, right: 8, left: 0, bottom: 0 }}>
          <CartesianGrid stroke={GRID} strokeDasharray="3 3" vertical={false} />
          <XAxis dataKey="step" type="number" domain={["dataMin", "dataMax"]} tick={AXIS_TICK} tickLine={false} axisLine={false} />
          <YAxis domain={["auto", "auto"]} tick={AXIS_TICK} tickLine={false} axisLine={false} width={56} tickFormatter={(v: number) => simNum(v)} />
          {result.events.map((e) => (
            <ReferenceLine key={e.step + e.key} x={e.step} stroke={EVENT_FILL[e.key]} strokeDasharray="4 3" label={{ value: EVENTS[e.key].name, position: "insideTopRight", fill: "var(--muted)", fontSize: 11 }} />
          ))}
          <Tooltip
            contentStyle={TOOLTIP_STYLE}
            labelFormatter={(s) => `Step ${s}`}
            formatter={(v, name) => (Array.isArray(v) ? [`${simNum(Number(v[0]))} – ${simNum(Number(v[1]))}`, "10th–90th percentile"] : [simNum(Number(v)), name === "p50" ? "Median" : String(name)])}
          />
          <Area dataKey="band" stroke="none" fill="var(--sim)" fillOpacity={0.18} isAnimationActive={false} />
          <Line dataKey="p50" stroke="var(--sim)" strokeWidth={2} dot={false} isAnimationActive={false} />
        </ComposedChart>
      </ResponsiveContainer>
    </div>
  );
}

/** Experiment Lab: how volatility and drawdown change as the share of Momentum traders grows. */
export function SweepChart({ result, height = 240 }: { result: SweepResult; height?: number }) {
  const data = result.rows.map((r) => ({ share: `${Math.round(r.momentumShare * 100)}%`, vol: r.volatilityPct, dd: Math.abs(r.maxDrawdownPct) }));
  return (
    <div style={{ height }}>
      <ResponsiveContainer width="100%" height="100%">
        <ComposedChart data={data} margin={{ top: 8, right: 8, left: 0, bottom: 0 }}>
          <CartesianGrid stroke={GRID} strokeDasharray="3 3" vertical={false} />
          <XAxis dataKey="share" tick={AXIS_TICK} tickLine={false} axisLine={false} label={{ value: "Momentum traders", position: "insideBottom", offset: -2, fill: "var(--muted)", fontSize: 11 }} height={36} />
          <YAxis yAxisId="v" tick={AXIS_TICK} tickLine={false} axisLine={false} width={44} tickFormatter={(v: number) => v.toFixed(2) + "%"} />
          <YAxis yAxisId="d" orientation="right" tick={AXIS_TICK} tickLine={false} axisLine={false} width={44} tickFormatter={(v: number) => v.toFixed(0) + "%"} />
          <Tooltip contentStyle={TOOLTIP_STYLE} formatter={(v, name) => [name === "vol" ? Number(v).toFixed(3) + "%" : simPct(-Number(v), 1), name === "vol" ? "Step volatility" : "Largest fall from a peak"]} />
          <Legend wrapperStyle={{ fontSize: 12 }} formatter={(v) => (v === "vol" ? "Step volatility" : "Largest fall from a peak")} />
          <Bar yAxisId="d" dataKey="dd" fill="var(--down)" fillOpacity={0.35} radius={[4, 4, 0, 0]} isAnimationActive={false} />
          <Line yAxisId="v" dataKey="vol" stroke="var(--sim)" strokeWidth={2} isAnimationActive={false} />
        </ComposedChart>
      </ResponsiveContainer>
    </div>
  );
}
